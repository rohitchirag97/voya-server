// Greedy mini-game: one global round every ~38s. resultItem/settledAt are set together, in the payout transaction.
export const greedyRounds = pgTable(
  "greedy_rounds",
  {
    id: bigserial("id", { mode: "number" }).primaryKey(),
    game: text("game").notNull().default("jungle"), // which skin's loop owns the round: "jungle" | "galaxy"; each has its own rounds, history and leaderboard
    number: integer("number").notNull(), // the round number players see, counted per game (id is shared across games)
    betEndsAt: ts("bet_ends_at").notNull(),
    resultItem: integer("result_item"),
    settledAt: ts("settled_at"),
    createdAt: createdAt(),
  },
  (t) => [
    index("greedy_rounds_unsettled").on(t.id).where(sql`${t.settledAt} is null`),
    index("greedy_rounds_game_created").on(t.game, t.createdAt),
    index("greedy_rounds_game_id").on(t.game, t.id),
    uniqueIndex("greedy_rounds_game_number").on(t.game, t.number),
  ],
);

// One row per user per item per round; repeat bets add to `amount`.
export const greedyBets = pgTable(
  "greedy_bets",
  {
    roundId: bigint("round_id", { mode: "number" }).notNull().references(() => greedyRounds.id),
    userId: uuid("user_id").notNull().references(() => users.id),
    item: integer("item").notNull(),
    amount: integer("amount").notNull(),
  },
  (t) => [primaryKey({ columns: [t.roundId, t.userId, t.item] }), check("greedy_bet_positive", sql`${t.amount} > 0`)],
);

// Rocket (crash) game. The crash point is drawn when the round opens, before any bet, and kept secret until the
// crash; `hash` = sha256("<salt>:<crash100>") is shown before launch so players can verify it afterwards.
// Multipliers are stored in hundredths: 245 = 2.45x.
export const rocketRounds = pgTable(
  "rocket_rounds",
  {
    id: bigserial("id", { mode: "number" }).primaryKey(),
    number: integer("number").notNull(),
    crash100: integer("crash100").notNull(),
    salt: text("salt").notNull(),
    hash: text("hash").notNull(),
    launchAt: ts("launch_at").notNull(), // betting closes and the flight starts
    crashedAt: ts("crashed_at"), // set with the settlement, in one transaction
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex("rocket_rounds_number").on(t.number),
    index("rocket_rounds_open").on(t.id).where(sql`${t.crashedAt} is null`),
    index("rocket_rounds_created").on(t.createdAt),
    check("rocket_crash_range", sql`${t.crash100} >= 100`),
  ],
);

// One stake per user per bet panel (slot 0 or 1) per round; repeat bets on a panel add to its amount.
// cashed100/payout are set when that panel cashes out (or its auto cash-out fires at settlement).
export const rocketBets = pgTable(
  "rocket_bets",
  {
    roundId: bigint("round_id", { mode: "number" }).notNull().references(() => rocketRounds.id),
    userId: uuid("user_id").notNull().references(() => users.id),
    slot: integer("slot").notNull().default(0),
    amount: integer("amount").notNull(),
    auto100: integer("auto100"),
    cashed100: integer("cashed100"),
    payout: integer("payout"),
    createdAt: createdAt(),
  },
  (t) => [
    primaryKey({ columns: [t.roundId, t.userId, t.slot] }),
    check("rocket_bet_positive", sql`${t.amount} > 0`),
    check("rocket_bet_slot", sql`${t.slot} in (0, 1)`),
  ],
);

// Live PK: two live streams head to head. Room A's host invites room B's host; once accepted both rooms show the
// split screen. Each side's score = gift coins received in its own room during [startedAt, endsAt).
export const livePks = pgTable(
  "live_pks",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    roomA: uuid("room_a").notNull().references(() => rooms.id),
    roomB: uuid("room_b").notNull().references(() => rooms.id),
    status: livePkStatus("status").notNull().default("INVITED"),
    minutes: integer("minutes").notNull(),
    startedAt: ts("started_at"),
    endsAt: ts("ends_at"),
    winnerRoom: uuid("winner_room"),
    createdAt: createdAt(),
  },
  (t) => [
    // A room is in at most one pending/running battle at a time (either side).
    uniqueIndex("live_pk_one_open_a").on(t.roomA).where(sql`${t.status} in ('INVITED', 'ACTIVE')`),
    uniqueIndex("live_pk_one_open_b").on(t.roomB).where(sql`${t.status} in ('INVITED', 'ACTIVE')`),
  ],
);

// ---------- CP (relationships) ----------
// LOVE: 1 per user; BESTIE: up to 4; SIBLING: up to 7 (labelled BROTHER or SISTER by whoever proposed).
export const cpType = pgEnum("cp_type", ["LOVE", "BESTIE", "SIBLING"]);
export const cpProposalStatus = pgEnum("cp_proposal_status", ["PENDING", "ACCEPTED", "DECLINED", "EXPIRED", "CANCELLED"]);

// The proposer pays up front (ledger CP_PROPOSAL); declined, expired or cancelled proposals are refunded (CP_REFUND).
export const cpProposals = pgTable(
  "cp_proposals",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    fromId: uuid("from_id").notNull().references(() => users.id),
    toId: uuid("to_id").notNull().references(() => users.id),
    type: cpType("type").notNull(),
    label: text("label"), // SIBLING only: BROTHER | SISTER
    price: integer("price").notNull(),
    status: cpProposalStatus("status").notNull().default("PENDING"),
    expiresAt: ts("expires_at").notNull(),
    respondedAt: ts("responded_at"),
    createdAt: createdAt(),
  },
  (t) => [
    check("cp_not_self", sql`${t.fromId} <> ${t.toId}`),
    uniqueIndex("cp_one_pending_per_pair").on(t.fromId, t.toId).where(sql`${t.status} = 'PENDING'`),
    index("cp_proposals_pending_expiry").on(t.expiresAt).where(sql`${t.status} = 'PENDING'`),
  ],
);

// An active relationship has endedAt null. userA < userB, so a pair of people has one canonical row.
export const cpPairs = pgTable(
  "cp_pairs",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userA: uuid("user_a").notNull().references(() => users.id),
    userB: uuid("user_b").notNull().references(() => users.id),
    type: cpType("type").notNull(),
    label: text("label"),
    proposalId: uuid("proposal_id").notNull().references(() => cpProposals.id),
    intimacy: integer("intimacy").notNull().default(0), // CP level points (see lib/cpLevels.ts)
    createdAt: createdAt(),
    endedAt: ts("ended_at"),
    endedBy: uuid("ended_by").references(() => users.id),
  },
  (t) => [
    check("cp_pair_order", sql`${t.userA} < ${t.userB}`),
    // Two people share at most one active relationship, of any type.
    uniqueIndex("cp_pairs_one_active").on(t.userA, t.userB).where(sql`${t.endedAt} is null`),
    index("cp_pairs_a").on(t.userA).where(sql`${t.endedAt} is null`),
    index("cp_pairs_b").on(t.userB).where(sql`${t.endedAt} is null`),
  ],
);

