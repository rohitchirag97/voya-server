// Profile decorations. The artwork is SVG markup stored here, so new items need no app release.
export const cosmetics = pgTable("cosmetics", {
  id: text("id").primaryKey(),
  kind: cosmeticKind("kind").notNull(),
  name: text("name").notNull(),
  svg: text("svg").notNull(),
  // Animated version (an .svga path under public/, e.g. games/fx/svip/frame/1.svga): the app plays it in place of the svg.
  svga: text("svga"),
  // Chat bubbles: { gradient: [from, to], border, text }. The svg is the corner ornament.
  style: jsonb("style").$type<{ gradient: string[]; border: string; text: string }>(),
  enabled: boolean("enabled").notNull().default(true),
  // SVIP tier needed to equip and show it (0 = anyone). A lapsed tier hides the item until earned again.
  minSvip: integer("min_svip").notNull().default(0),
  // Prize items (admin panel > Items): only people who own one (user_cosmetics, until it expires) can wear it.
  exclusive: boolean("exclusive").notNull().default(false),
  sortOrder: integer("sort_order").notNull().default(0),
  createdAt: createdAt(),
});

