export const rooms = pgTable(
  "rooms",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    zegoRoomId: text("zego_room_id").notNull().unique(),
    hostUserId: uuid("host_user_id").notNull().references(() => users.id),
    title: text("title").notNull(),
    category: text("category"),
    coverUrl: text("cover_url"),
    status: roomStatus("status").notNull().default("CREATED"),
    seatCount: integer("seat_count").notNull(),
    version: integer("version").notNull().default(0),
    listenerCount: integer("listener_count").notNull().default(0),
    createdAt: createdAt(),
    startedAt: ts("started_at"),
    endedAt: ts("ended_at"),
    // Charisma counter: while set, each person's charisma = coins of gifts they received in this room since then. null = off.
    charismaStartedAt: ts("charisma_started_at"),
    // Running PK 1v1 battle between two seated people (null = none). Scores = gift coins each receives in this room in [startedAt, endsAt).
    pk: jsonb("pk").$type<{ a: string; b: string; startedAt: string; endsAt: string }>(),
    // Ludo mode (null = off): the lobby or running game, see lib/ludo.ts. Seats show in one row with the board below.
    ludo: jsonb("ludo").$type<LudoState>(),
    // Video mode (null = off): the shared YouTube player under the seat row, see services/video.ts.
    video: jsonb("video").$type<VideoState>(),
    // PUBLIC: listed, anyone joins. LOCKED: listed with a lock; joining needs the 4-digit password (hashed here).
    // PRIVATE: hidden from lists and profiles; only the owner and room admins can enter.
    privacy: roomPrivacy("privacy").notNull().default("PUBLIC"),
    passwordHash: text("password_hash"),
    // Room settings (owner/admins): backdrop preset, "X joined" notices, full-screen gift effects + banners.
    background: text("background").notNull().default("night"),
    backgroundUrl: text("background_url"), // a custom photo backdrop (wins over the preset); null = use the preset
    showEntry: boolean("show_entry").notNull().default(true),
    giftAnimations: boolean("gift_animations").notNull().default(true),
    // AUDIO: the permanent party room. LIVE: a video live stream (seat 0 = host camera, 1-3 = co-hosts), ended when the host stops.
    kind: roomKind("kind").notNull().default("AUDIO"),
    // Pinned to the top of the room list, in slot order (1-4). Slot 1 is the official help room (`official`),
    // set by src/db/officialRoom.ts; staff pin others. Everything else is ranked below them (services/rooms listRooms).
    pinSlot: integer("pin_slot"),
    official: boolean("official").notNull().default(false),
  },
  (t) => [
    check("rooms_seat_count", sql`${t.seatCount} in (4, 8, 10, 12, 16, 20)`),
    check("rooms_pin_slot", sql`${t.pinSlot} between 1 and 4`),
    uniqueIndex("rooms_pin_slot_unique").on(t.pinSlot).where(sql`${t.pinSlot} is not null`),
    // One open room of each kind per host (an audio room and a live stream can run side by side).
    uniqueIndex("rooms_one_open_per_host_kind").on(t.hostUserId, t.kind).where(sql`${t.status} in ('CREATED', 'LIVE')`),
    index("rooms_status_started").on(t.status, t.startedAt),
  ],
);

