export const users = pgTable(
  "users",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // A user signs in with a phone, a Google account, or both.
    phone: text("phone").unique(),
    googleSub: text("google_sub").unique(),
    displayName: text("display_name"),
    avatarUrl: text("avatar_url"),
    bio: text("bio"),
    status: userStatus("status").notNull().default("ACTIVE"),
    // Recharge points (1 per ₹1 recharged); the level comes from level_thresholds. Never decreases.
    xp: integer("xp").notNull().default(0),
    // Equipped decorations (null = none).
    avatarFrameId: text("avatar_frame_id").references(() => cosmetics.id),
    cardDecorId: text("card_decor_id").references(() => cosmetics.id),
    chatBubbleId: text("chat_bubble_id").references(() => cosmetics.id),
    entryEffectId: text("entry_effect_id").references(() => cosmetics.id), // an owned entry effect, played on entering rooms
    // Public 10-digit number shown on the profile; generated by gen_public_id() (migration 0013).
    publicId: bigint("public_id", { mode: "number" }).notNull().unique().default(sql`gen_public_id()`),
    // Premium short ID: 3-9 capital letters/digits (stored uppercase), granted by staff. Never clashes with a 10-digit public id.
    specialId: text("special_id").unique(),
    specialIdExpiresAt: ts("special_id_expires_at"), // a Special ID won for N days; null = keeps it
    // App staff (null = regular user). Only set by src/db/grantStaff.ts, never through the API; drives the Official mark.
    staffRole: staffRole("staff_role"),
    noticesSeenAt: ts("notices_seen_at"), // inbox Notices tile: notices after this are unread
    // About me (all optional). Age and zodiac are worked out from the birthday in the app.
    gender: gender("gender"),
    birthday: date("birthday", { mode: "string" }),
    hometown: text("hometown"),
    interests: text("interests").array().notNull().default(sql`'{}'`), // tags from lib/profileOptions INTERESTS
    // Badges shown on the badge wall at the top of the profile, in order (max 9; only ones still owned show).
    pinnedBadges: text("pinned_badges").array().notNull().default(sql`'{}'`),
    // Profile cover photos (uploads), shown as a slideshow; first is the main one. Max 6 (lib/profileOptions).
    coverUrls: text("cover_urls").array().notNull().default(sql`'{}'`),
    bannedUntil: ts("banned_until"), // status BANNED: when it lifts by itself (null = lifetime)
    banReason: text("ban_reason"), // shown to them when they try to sign in
    lastSeenAt: ts("last_seen_at"), // when their app last connected or went away ("Last seen …"); online is live (isOnline)
    createdAt: createdAt(),
    updatedAt: ts("updated_at").notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex("users_display_name_lower").on(sql`lower(${t.displayName})`),
    check("special_id_format", sql`${t.specialId} ~ '^[A-Z0-9]{3,9}$'`),
    // Only one app owner (the gold tick).
    uniqueIndex("users_single_owner").on(t.staffRole).where(sql`${t.staffRole} = 'OWNER'`),
  ],
);

