// Home carousel placement for event banners and notices: the Live tab, the Rooms tab, or both.
export type HomeTab = "BOTH" | "LIVE" | "ROOMS";
// A prize is any mix of items (built by drag and drop in the panel). Days: how long it lasts; null = forever.
export type RewardItem =
  | { type: "COINS"; amount: number }
  | { type: "BADGE"; id: string; days: number | null }
  | { type: "ITEM"; id: string; days: number | null } // a frame, chat bubble or entry effect (cosmetics)
  | { type: "SPECIAL_ID"; days: number | null } // a voucher: the winner picks their own Special ID
  | { type: "SVIP"; tier: number; days: number };
export type EventReward = { items: RewardItem[] };
export type EventMetric = "GIFTS_SENT" | "GIFTS_RECEIVED" | "ROOM_GIFTS" | "RECHARGE" | "GAME_WINS" | "CP_POINTS";
export type EventGame = "ALL" | "GREEDY_JUNGLE" | "GREEDY_GALAXY" | "ROCKET";
// Optional limits on what counts: which gifts, and who can take part.
export type EventFilter =
  | { type: "EVENT_GIFTS" } // only the event's own gift category
  | { type: "GIFT_CATEGORIES"; ids: number[] }
  | { type: "HOSTS_ONLY" } // agency hosts
  | { type: "JOINED_AFTER"; date: string } // YYYY-MM-DD, India time
  | { type: "MIN_LEVEL"; level: number };
// What a leaderboard or task counts: coins of gifts (sent, received, per room), coins from recharges, game winnings
// (one game or all), or CP points (pairs; both partners share the prize). Filters narrow it.
export type EventCounting = { metric: EventMetric; game: EventGame; filters: EventFilter[] };
export type EventConfig = {
  page: { headerUrl: string | null; color: string; description: string; rules: string };
  // Leaderboards: ranks shown and prizes by rank range; `min`: the score a rank needs to win its prize (so a tiny total
  // can't take a top prize).
  boards: (EventCounting & { id: string; title: string; size: number; rewards: (EventReward & { from: number; to: number; min?: number })[] })[];
  // Tasks: a per-user target over the event, or each day (India time) if daily. Never CP (a pair isn't one person).
  tasks: (EventCounting & { id: string; title: string; target: number; daily: boolean; reward: EventReward })[];
};
export type EventRepeat = "NONE" | "WEEKLY" | "MONTHLY";
export const events = pgTable(
  "events",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    title: text("title").notNull(),
    startsAt: ts("starts_at").notNull(),
    endsAt: ts("ends_at").notNull(),
    published: boolean("published").notNull().default(false), // drafts are seen by staff only
    bannerUrl: text("banner_url"), // games/events/<file>
    bannerHome: boolean("banner_home").notNull().default(true),
    bannerRoom: boolean("banner_room").notNull().default(true),
    homeTab: text("home_tab").$type<HomeTab>().notNull().default("BOTH"), // which home tab shows the banner
    sortOrder: integer("sort_order").notNull().default(0),
    giftCategoryId: integer("gift_category_id").references(() => giftCategories.id), // event gifts: shown only while live
    config: jsonb("config").$type<EventConfig>().notNull(),
    paidOutAt: ts("paid_out_at"), // rewards approved
    // Weekly/monthly: when this period ends the server opens the next one (same look, fresh boards); repeatedInto = it.
    repeat: text("repeat").$type<EventRepeat>().notNull().default("NONE"),
    repeatedInto: uuid("repeated_into"),
    createdAt: createdAt(),
  },
  (t) => [index("events_window").on(t.published, t.startsAt, t.endsAt), check("event_window", sql`${t.endsAt} > ${t.startsAt}`)],
);
// Rewards given out when staff approved an event's payouts; one row per user per prize (source), so nothing pays twice.
export const eventPayouts = pgTable(
  "event_payouts",
  {
    id: bigserial("id", { mode: "number" }).primaryKey(),
    eventId: uuid("event_id").notNull().references(() => events.id),
    userId: uuid("user_id").notNull().references(() => users.id),
    source: text("source").notNull(), // "board:<id>:<rank>" or "task:<id>" / "task:<id>:<YYYY-MM-DD>"
    reward: jsonb("reward").$type<EventReward>().notNull(),
    approvedBy: uuid("approved_by").notNull().references(() => users.id),
    createdAt: createdAt(),
  },
  (t) => [uniqueIndex("event_payouts_once").on(t.eventId, t.userId, t.source)],
);

